
-- SnowCost: Incremental Transaction Pipeline
-- Purpose:
--   1. Merge staged transactions into RAW.
--   2. Merge staged transactions into CORE with normalization.
--   3. Refresh affected dates in both analytical marts.
--   4. Support safe reruns of the same staged batch.
--
-- Prerequisite:
--   SNOWCOST.RAW.TRANSACTIONS_STAGE contains the incoming batch.
--   Review the source batch before executing this script.

USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;

-- 1. Merge staged records into RAW.
MERGE INTO SNOWCOST.RAW.TRANSACTIONS AS target
USING (
    SELECT *
    FROM SNOWCOST.RAW.TRANSACTIONS_STAGE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TRANSACTION_ID
        ORDER BY INGESTED_AT DESC
    ) = 1
) AS source
ON target.TRANSACTION_ID = source.TRANSACTION_ID


WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_ID,
    CUSTOMER_ID,
    TRANSACTION_TS,
    AMOUNT,
    CURRENCY,
    MERCHANT_CATEGORY,
    COUNTRY_CODE,
    STATUS,
    IS_SUSPICIOUS,
    INGESTED_AT
)
VALUES (
    source.TRANSACTION_ID,
    source.CUSTOMER_ID,
    source.TRANSACTION_TS,
    source.AMOUNT,
    source.CURRENCY,
    source.MERCHANT_CATEGORY,
    source.COUNTRY_CODE,
    source.STATUS,
    source.IS_SUSPICIOUS,
    source.INGESTED_AT
);

-- 2. Merge staged transactions into CORE.
-- Use the corresponding RAW records so CORE reflects the RAW layer.
MERGE INTO SNOWCOST.CORE.TRANSACTIONS_CLEAN AS target
USING (
    SELECT
        r.TRANSACTION_ID,
        r.CUSTOMER_ID,
        r.TRANSACTION_TS,
        r.AMOUNT,
        UPPER(TRIM(r.CURRENCY)) AS CURRENCY,
        UPPER(TRIM(r.MERCHANT_CATEGORY)) AS MERCHANT_CATEGORY,
        UPPER(TRIM(r.COUNTRY_CODE)) AS COUNTRY_CODE,
        UPPER(TRIM(r.STATUS)) AS STATUS,
        COALESCE(r.IS_SUSPICIOUS, FALSE) AS IS_SUSPICIOUS,
        r.INGESTED_AT
    FROM SNOWCOST.RAW.TRANSACTIONS AS r
    WHERE EXISTS (
        SELECT 1
        FROM SNOWCOST.RAW.TRANSACTIONS_STAGE AS s
        WHERE s.TRANSACTION_ID = r.TRANSACTION_ID
    )
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY r.TRANSACTION_ID
        ORDER BY r.INGESTED_AT DESC
    ) = 1
) AS source
ON target.TRANSACTION_ID = source.TRANSACTION_ID


WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_ID,
    CUSTOMER_ID,
    TRANSACTION_TS,
    AMOUNT,
    CURRENCY,
    MERCHANT_CATEGORY,
    COUNTRY_CODE,
    STATUS,
    IS_SUSPICIOUS,
    INGESTED_AT
)
VALUES (
    source.TRANSACTION_ID,
    source.CUSTOMER_ID,
    source.TRANSACTION_TS,
    source.AMOUNT,
    source.CURRENCY,
    source.MERCHANT_CATEGORY,
    source.COUNTRY_CODE,
    source.STATUS,
    source.IS_SUSPICIOUS,
    source.INGESTED_AT
);

-- 3. Refresh affected dates in DAILY_TRANSACTION_SUMMARY.
-- Recompute complete aggregates for affected dates, not just new rows.
MERGE INTO SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY AS target
USING (
    WITH affected_dates AS (
        SELECT DISTINCT TO_DATE(TRANSACTION_TS) AS TRANSACTION_DATE
        FROM SNOWCOST.RAW.TRANSACTIONS_STAGE
        WHERE TRANSACTION_TS IS NOT NULL
    )
    SELECT
        TO_DATE(c.TRANSACTION_TS) AS TRANSACTION_DATE,
        c.COUNTRY_CODE,
        c.CURRENCY,
        COUNT(*) AS TRANSACTION_COUNT,
        ROUND(SUM(c.AMOUNT), 2) AS TOTAL_AMOUNT,
        ROUND(AVG(c.AMOUNT), 2) AS AVG_AMOUNT,
        COALESCE(COUNT_IF(c.IS_SUSPICIOUS), 0) AS SUSPICIOUS_COUNT,
        COALESCE(COUNT_IF(c.STATUS = 'DECLINED'), 0) AS DECLINED_COUNT
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN AS c
    JOIN affected_dates AS d
        ON TO_DATE(c.TRANSACTION_TS) = d.TRANSACTION_DATE
    GROUP BY
        TO_DATE(c.TRANSACTION_TS),
        c.COUNTRY_CODE,
        c.CURRENCY
) AS source
ON target.TRANSACTION_DATE = source.TRANSACTION_DATE
   AND target.COUNTRY_CODE = source.COUNTRY_CODE
   AND target.CURRENCY = source.CURRENCY

WHEN MATCHED THEN UPDATE SET
    target.TRANSACTION_COUNT = source.TRANSACTION_COUNT,
    target.TOTAL_AMOUNT = source.TOTAL_AMOUNT,
    target.AVG_AMOUNT = source.AVG_AMOUNT,
    target.SUSPICIOUS_COUNT = source.SUSPICIOUS_COUNT,
    target.DECLINED_COUNT = source.DECLINED_COUNT

WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_DATE,
    COUNTRY_CODE,
    CURRENCY,
    TRANSACTION_COUNT,
    TOTAL_AMOUNT,
    AVG_AMOUNT,
    SUSPICIOUS_COUNT,
    DECLINED_COUNT
)
VALUES (
    source.TRANSACTION_DATE,
    source.COUNTRY_CODE,
    source.CURRENCY,
    source.TRANSACTION_COUNT,
    source.TOTAL_AMOUNT,
    source.AVG_AMOUNT,
    source.SUSPICIOUS_COUNT,
    source.DECLINED_COUNT
);

-- 4. Refresh affected dates in DAILY_CATEGORY_SUMMARY.
MERGE INTO SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY AS target
USING (
    WITH affected_dates AS (
        SELECT DISTINCT TO_DATE(TRANSACTION_TS) AS TRANSACTION_DATE
        FROM SNOWCOST.RAW.TRANSACTIONS_STAGE
        WHERE TRANSACTION_TS IS NOT NULL
    )
    SELECT
        TO_DATE(c.TRANSACTION_TS) AS TRANSACTION_DATE,
        c.MERCHANT_CATEGORY,
        COUNT(*) AS TRANSACTION_COUNT,
        ROUND(SUM(c.AMOUNT), 2) AS TOTAL_AMOUNT,
        ROUND(AVG(c.AMOUNT), 2) AS AVG_AMOUNT
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN AS c
    JOIN affected_dates AS d
        ON TO_DATE(c.TRANSACTION_TS) = d.TRANSACTION_DATE
    GROUP BY
        TO_DATE(c.TRANSACTION_TS),
        c.MERCHANT_CATEGORY
) AS source
ON target.TRANSACTION_DATE = source.TRANSACTION_DATE
   AND target.MERCHANT_CATEGORY = source.MERCHANT_CATEGORY

WHEN MATCHED THEN UPDATE SET
    target.TRANSACTION_COUNT = source.TRANSACTION_COUNT,
    target.TOTAL_AMOUNT = source.TOTAL_AMOUNT,
    target.AVG_AMOUNT = source.AVG_AMOUNT

WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_DATE,
    MERCHANT_CATEGORY,
    TRANSACTION_COUNT,
    TOTAL_AMOUNT,
    AVG_AMOUNT
)
VALUES (
    source.TRANSACTION_DATE,
    source.MERCHANT_CATEGORY,
    source.TRANSACTION_COUNT,
    source.TOTAL_AMOUNT,
    source.AVG_AMOUNT
);

-- 5. End-of-run reconciliation.
WITH layer_counts AS (
    SELECT
        'RAW' AS LAYER_NAME,
        COUNT(*) AS ROW_COUNT,
        COUNT(DISTINCT TRANSACTION_ID) AS UNIQUE_IDS
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'CORE',
        COUNT(*),
        COUNT(DISTINCT TRANSACTION_ID)
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'DAILY_TRANSACTION_SUMMARY',
        COALESCE(SUM(TRANSACTION_COUNT), 0),
        COALESCE(SUM(TRANSACTION_COUNT), 0)
    FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY

    UNION ALL

    SELECT
        'DAILY_CATEGORY_SUMMARY',
        COALESCE(SUM(TRANSACTION_COUNT), 0),
        COALESCE(SUM(TRANSACTION_COUNT), 0)
    FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY
)
SELECT
    LAYER_NAME,
    ROW_COUNT,
    UNIQUE_IDS,
    CASE
        WHEN ROW_COUNT = UNIQUE_IDS THEN 'PASS'
        ELSE 'FAIL'
    END AS ID_CHECK
FROM layer_counts
ORDER BY LAYER_NAME;