-- SnowCost: Data Quality and Reconciliation Checks
-- Purpose:
--   1. Validate required transaction fields and values.
--   2. Reconcile raw, core, and analytical mart transaction counts.
--   3. Persist reconciliation results in the audit table.

USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;

-- 1. Create the audit table if it does not exist
CREATE TABLE IF NOT EXISTS SNOWCOST.AUDIT.DATA_QUALITY_AUDIT (
    AUDIT_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    CHECK_NAME VARCHAR,
    SOURCE_TABLE VARCHAR,
    EXPECTED_VALUE NUMBER,
    ACTUAL_VALUE NUMBER,
    CHECK_STATUS VARCHAR,
    CHECKED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Inspect source and core data quality.
-- COALESCE ensures checks return 0 instead of NULL when no rows match.

SELECT
    'RAW' AS DATA_LAYER,
    COALESCE(COUNT_IF(TRANSACTION_ID IS NULL), 0) AS NULL_TRANSACTION_IDS,
    COALESCE(COUNT_IF(CUSTOMER_ID IS NULL), 0) AS NULL_CUSTOMER_IDS,
    COALESCE(COUNT_IF(TRANSACTION_TS IS NULL), 0) AS NULL_TIMESTAMPS,
    COALESCE(COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0), 0) AS INVALID_AMOUNTS,
    COALESCE(
        COUNT_IF(STATUS IS NULL OR STATUS NOT IN ('SETTLED', 'DECLINED')),
        0
    ) AS INVALID_STATUSES
FROM SNOWCOST.RAW.TRANSACTIONS

UNION ALL

SELECT
    'CORE' AS DATA_LAYER,
    COALESCE(COUNT_IF(TRANSACTION_ID IS NULL), 0) AS NULL_TRANSACTION_IDS,
    COALESCE(COUNT_IF(CUSTOMER_ID IS NULL), 0) AS NULL_CUSTOMER_IDS,
    COALESCE(COUNT_IF(TRANSACTION_TS IS NULL), 0) AS NULL_TIMESTAMPS,
    COALESCE(COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0), 0) AS INVALID_AMOUNTS,
    COALESCE(
        COUNT_IF(STATUS IS NULL OR STATUS NOT IN ('SETTLED', 'DECLINED')),
        0
    ) AS INVALID_STATUSES
FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN;

-- 2A. Persist field-level data quality results for RAW.
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    CHECK_NAME,
    'SNOWCOST.RAW.TRANSACTIONS',
    0,
    ACTUAL_VALUE,
    CASE WHEN ACTUAL_VALUE = 0 THEN 'PASS' ELSE 'FAIL' END
FROM (
    SELECT
        'RAW_NULL_TRANSACTION_IDS' AS CHECK_NAME,
        COALESCE(COUNT_IF(TRANSACTION_ID IS NULL), 0) AS ACTUAL_VALUE
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'RAW_NULL_CUSTOMER_IDS',
        COALESCE(COUNT_IF(CUSTOMER_ID IS NULL), 0)
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'RAW_NULL_TIMESTAMPS',
        COALESCE(COUNT_IF(TRANSACTION_TS IS NULL), 0)
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'RAW_INVALID_AMOUNTS',
        COALESCE(COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0), 0)
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'RAW_INVALID_STATUSES',
        COALESCE(
            COUNT_IF(STATUS IS NULL OR UPPER(TRIM(STATUS))
                NOT IN ('SETTLED', 'DECLINED')),
            0
        )
    FROM SNOWCOST.RAW.TRANSACTIONS
);

-- 2B. Persist field-level data quality results for CORE.
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    CHECK_NAME,
    'SNOWCOST.CORE.TRANSACTIONS_CLEAN',
    0,
    ACTUAL_VALUE,
    CASE WHEN ACTUAL_VALUE = 0 THEN 'PASS' ELSE 'FAIL' END
FROM (
    SELECT
        'CORE_NULL_TRANSACTION_IDS' AS CHECK_NAME,
        COALESCE(COUNT_IF(TRANSACTION_ID IS NULL), 0) AS ACTUAL_VALUE
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'CORE_NULL_CUSTOMER_IDS',
        COALESCE(COUNT_IF(CUSTOMER_ID IS NULL), 0)
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'CORE_NULL_TIMESTAMPS',
        COALESCE(COUNT_IF(TRANSACTION_TS IS NULL), 0)
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'CORE_INVALID_AMOUNTS',
        COALESCE(COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0), 0)
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'CORE_INVALID_STATUSES',
        COALESCE(
            COUNT_IF(
                STATUS IS NULL
                OR UPPER(TRIM(STATUS)) NOT IN ('SETTLED', 'DECLINED')
            ),
            0
        ) AS INVALID_STATUSES
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN
);

-- 3. Persist core-to-daily-mart reconciliation
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    'CORE_TO_MART_ROW_RECONCILIATION',
    'SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY',
    (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY),
    CASE
        WHEN (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN)
           = (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
              FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY)
        THEN 'PASS'
        ELSE 'FAIL'
    END;

-- 4. Persist core-to-category-mart reconciliation
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    'CORE_TO_CATEGORY_MART_ROW_RECONCILIATION',
    'SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY',
    (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY),
    CASE
        WHEN (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN)
           = (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
              FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY)
        THEN 'PASS'
        ELSE 'FAIL'
    END;

-- 5. Review latest audit results
SELECT
    CHECK_NAME,
    SOURCE_TABLE,
    EXPECTED_VALUE,
    ACTUAL_VALUE,
    CHECK_STATUS,
    CHECKED_AT
FROM SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
ORDER BY CHECKED_AT DESC
LIMIT 20;