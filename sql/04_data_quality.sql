-- SnowCost: Data Quality and Reconciliation Checks
-- Purpose:
--   1. Validate required transaction fields and values.
--   2. Reconcile raw, core, and analytical mart transaction counts.
--   3. Persist reconciliation results in the audit table.

USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;

-- 1. Create the audit table if it does not exist
CREATE TABLE IF NOT EXISTS SNOWCOST.AUDIT.DATA_QUALITY_AUDIT (
    AUDIT_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    CHECK_NAME VARCHAR,
    SOURCE_TABLE VARCHAR,
    EXPECTED_VALUE NUMBER,
    ACTUAL_VALUE NUMBER,
    CHECK_STATUS VARCHAR,
    CHECKED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Inspect source and core data quality
SELECT
    'RAW' AS DATA_LAYER,
    COUNT_IF(TRANSACTION_ID IS NULL) AS NULL_TRANSACTION_IDS,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(TRANSACTION_TS IS NULL) AS NULL_TIMESTAMPS,
    COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0) AS INVALID_AMOUNTS,
    COUNT_IF(STATUS IS NULL OR STATUS NOT IN ('SETTLED', 'DECLINED')) AS INVALID_STATUSES
FROM SNOWCOST.RAW.TRANSACTIONS

UNION ALL

SELECT
    'CORE' AS DATA_LAYER,
    COUNT_IF(TRANSACTION_ID IS NULL) AS NULL_TRANSACTION_IDS,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(TRANSACTION_TS IS NULL) AS NULL_TIMESTAMPS,
    COUNT_IF(AMOUNT IS NULL OR AMOUNT < 0) AS INVALID_AMOUNTS,
    COUNT_IF(STATUS IS NULL OR STATUS NOT IN ('SETTLED', 'DECLINED')) AS INVALID_STATUSES
FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN;

-- 3. Persist core-to-daily-mart reconciliation
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    'CORE_TO_MART_ROW_RECONCILIATION',
    'SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY',
    (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY),
    CASE
        WHEN (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN)
           = (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
              FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY)
        THEN 'PASS'
        ELSE 'FAIL'
    END;

-- 4. Persist core-to-category-mart reconciliation
INSERT INTO SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
    (CHECK_NAME, SOURCE_TABLE, EXPECTED_VALUE, ACTUAL_VALUE, CHECK_STATUS)
SELECT
    'CORE_TO_CATEGORY_MART_ROW_RECONCILIATION',
    'SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY',
    (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY),
    CASE
        WHEN (SELECT COUNT(*) FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN)
           = (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
              FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY)
        THEN 'PASS'
        ELSE 'FAIL'
    END;

-- 5. Review latest audit results
SELECT
    CHECK_NAME,
    SOURCE_TABLE,
    EXPECTED_VALUE,
    ACTUAL_VALUE,
    CHECK_STATUS,
    CHECKED_AT
FROM SNOWCOST.AUDIT.DATA_QUALITY_AUDIT
ORDER BY CHECKED_AT DESC
LIMIT 20;