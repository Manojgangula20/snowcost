-- SnowCost: Core Transformations and Analytical Marts
-- Purpose:
--   1. Deduplicate raw transactions into a cleaned core table.
--   2. Build daily country/currency metrics.
--   3. Build daily merchant-category metrics.
--
-- NOTE:
-- This is a full rebuild of the derived tables.
-- Re-running replaces these derived tables; it does not modify RAW.TRANSACTIONS.

USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;

-- 1. Clean and deduplicate transactions
CREATE OR REPLACE TABLE SNOWCOST.CORE.TRANSACTIONS_CLEAN AS
SELECT
    TRANSACTION_ID,
    CUSTOMER_ID,
    TRANSACTION_TS,
    AMOUNT,
    UPPER(TRIM(CURRENCY)) AS CURRENCY,
    UPPER(TRIM(MERCHANT_CATEGORY)) AS MERCHANT_CATEGORY,
    UPPER(TRIM(COUNTRY_CODE)) AS COUNTRY_CODE,
    UPPER(TRIM(STATUS)) AS STATUS,
    COALESCE(IS_SUSPICIOUS, FALSE) AS IS_SUSPICIOUS,
    INGESTED_AT
FROM SNOWCOST.RAW.TRANSACTIONS
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TRANSACTION_ID
    ORDER BY INGESTED_AT DESC
) = 1;

-- 2. Daily transaction summary by country and currency
CREATE OR REPLACE TABLE SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY AS
SELECT
    TO_DATE(TRANSACTION_TS) AS TRANSACTION_DATE,
    COUNTRY_CODE,
    CURRENCY,
    COUNT(*) AS TRANSACTION_COUNT,
    ROUND(SUM(AMOUNT), 2) AS TOTAL_AMOUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_AMOUNT,
    COUNT_IF(IS_SUSPICIOUS) AS SUSPICIOUS_COUNT,
    COUNT_IF(STATUS = 'DECLINED') AS DECLINED_COUNT
FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN
GROUP BY
    TO_DATE(TRANSACTION_TS),
    COUNTRY_CODE,
    CURRENCY;

-- 3. Daily transaction summary by merchant category
CREATE OR REPLACE TABLE SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY AS
SELECT
    TO_DATE(TRANSACTION_TS) AS TRANSACTION_DATE,
    MERCHANT_CATEGORY,
    COUNT(*) AS TRANSACTION_COUNT,
    ROUND(SUM(AMOUNT), 2) AS TOTAL_AMOUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_AMOUNT
FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN
GROUP BY
    TO_DATE(TRANSACTION_TS),
    MERCHANT_CATEGORY;

-- 4. Verify source and derived-table counts
SELECT
    (SELECT COUNT(*)
     FROM SNOWCOST.RAW.TRANSACTIONS) AS RAW_ROWS,

    (SELECT COUNT(*)
     FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN) AS CORE_ROWS,

    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY) AS DAILY_MART_ROWS,

    (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
     FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY) AS CATEGORY_MART_ROWS;

-- 5. Preview the daily summary
SELECT *
FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY
ORDER BY TRANSACTION_DATE DESC
LIMIT 20;

-- 6. Preview the category summary
SELECT *
FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY
ORDER BY TRANSACTION_DATE DESC, MERCHANT_CATEGORY
LIMIT 20;