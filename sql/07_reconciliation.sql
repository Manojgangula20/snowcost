-- SnowCost: Cross-layer reconciliation
-- Purpose: Verify RAW/CORE uniqueness and compare mart totals with CORE.

USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;

WITH reconciliation AS (
    SELECT
        'RAW_UNIQUE_IDS' AS CHECK_NAME,
        COUNT(*) AS ACTUAL_VALUE,
        COUNT(DISTINCT TRANSACTION_ID) AS EXPECTED_VALUE
    FROM SNOWCOST.RAW.TRANSACTIONS

    UNION ALL

    SELECT
        'CORE_UNIQUE_IDS',
        COUNT(*),
        COUNT(DISTINCT TRANSACTION_ID)
    FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN

    UNION ALL

    SELECT
        'DAILY_TRANSACTION_SUMMARY',
        (SELECT COUNT(*)
         FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
        (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
         FROM SNOWCOST.MARTS.DAILY_TRANSACTION_SUMMARY)

    UNION ALL

    SELECT
        'DAILY_CATEGORY_SUMMARY',
        (SELECT COUNT(*)
         FROM SNOWCOST.CORE.TRANSACTIONS_CLEAN),
        (SELECT COALESCE(SUM(TRANSACTION_COUNT), 0)
         FROM SNOWCOST.MARTS.DAILY_CATEGORY_SUMMARY)
)
SELECT
    CHECK_NAME,
    ACTUAL_VALUE,
    EXPECTED_VALUE,
    CASE
        WHEN ACTUAL_VALUE = EXPECTED_VALUE THEN 'PASS'
        ELSE 'FAIL'
    END AS CHECK_STATUS
FROM reconciliation
ORDER BY CHECK_NAME;