
-- SnowCost: Initial Snowflake Setup
-- Purpose: Create the project warehouse, database, schemas, and raw table.
-- Run in a Snowflake SQL Worksheet using a role with the required privileges.

-- 1. Create the project warehouse
CREATE WAREHOUSE IF NOT EXISTS SNOWCOST_WH
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'SnowCost learning project warehouse';

-- 2. Create the database and schemas
CREATE DATABASE IF NOT EXISTS SNOWCOST;

CREATE SCHEMA IF NOT EXISTS SNOWCOST.RAW;
CREATE SCHEMA IF NOT EXISTS SNOWCOST.CORE;
CREATE SCHEMA IF NOT EXISTS SNOWCOST.MARTS;
CREATE SCHEMA IF NOT EXISTS SNOWCOST.AUDIT;

-- 3. Set the execution context
USE WAREHOUSE SNOWCOST_WH;
USE DATABASE SNOWCOST;
USE SCHEMA RAW;

-- 4. Create the raw transaction table
CREATE TABLE IF NOT EXISTS SNOWCOST.RAW.TRANSACTIONS (
    TRANSACTION_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR NOT NULL,
    TRANSACTION_TS TIMESTAMP_TZ,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(3),
    MERCHANT_CATEGORY VARCHAR,
    COUNTRY_CODE VARCHAR(2),
    STATUS VARCHAR,
    IS_SUSPICIOUS BOOLEAN,
    INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- 5. Verify the active session context
SELECT
    CURRENT_ACCOUNT() AS ACCOUNT_NAME,
    CURRENT_USER() AS USER_NAME,
    CURRENT_ROLE() AS ACTIVE_ROLE,
    CURRENT_WAREHOUSE() AS ACTIVE_WAREHOUSE,
    CURRENT_DATABASE() AS ACTIVE_DATABASE,
    CURRENT_SCHEMA() AS ACTIVE_SCHEMA;

-- 6. Verify that the raw table exists
SHOW TABLES LIKE 'TRANSACTIONS' IN SCHEMA SNOWCOST.RAW;
